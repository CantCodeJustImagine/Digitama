#!/usr/bin/env python3
"""Generates trainers.h (the boss ladders) and badges.h (their badges).

  python3 tools/gen_ladders.py

The ladders come from LADDERS / AREAS in digimon_data.py: per V-Pet version,
eight area bosses, four elite and a champion. The badges are DRAWN here, from
geometry -- eight shapes, coloured by the area boss's element -- so nothing in
them is anybody else's artwork.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import digimon_data as D

ROOT = os.path.join(os.path.dirname(__file__), '..')
PX = 32


def ident(name):
    return name.replace('.', '').replace(' ', '_').upper()


def trainers():
    o = ['#pragma once\n#include <stdint.h>\n#include "dex.h"\n\n',
         '// GENERATED by tools/gen_ladders.py from tools/digimon_data.py - do not edit\n',
         '//\n// The boss ladders: per V-Pet version, eight areas, four elite and a\n'
         '// champion. A boss brings its whole team and you bring whoever you have,\n'
         '// so attrition is the difficulty. Levels follow the stage clock.\n\n',
         '#define TRAINER_TEAM_MAX 6\n#define MAX_TRAINER_LEVEL 100\n\n',
         'struct TrainerMon {\n  uint16_t dex;\n  uint8_t level;\n};\n\n',
         'struct Trainer {\n  const char *name;\n  const char *place;   // the area, or ELITE / CHAMPION\n'
         '  uint8_t type;        // element, for the UI accent\n  uint8_t count;\n'
         '  TrainerMon team[TRAINER_TEAM_MAX];\n};\n\n',
         '#define TRAINER_COUNT 13\n#define TRAINER_GYMS 8\n#define TRAINER_ELITE4 4\n\n',
         'struct TrainerSet {\n  const Trainer *list;\n  const char *region;\n};\n\n']
    for ver, _lo, _hi, _st in D.VERSIONS:
        o.append('static const Trainer TRAINERS_%s[TRAINER_COUNT] = {\n' % ident(ver))
        for (name, el, team), place in zip(D.LADDERS[ver], D.AREAS[ver]):
            mons = ','.join('{%d,%d}' % t for t in team)
            o.append('  { %-15s %-16s T_%-9s %d, { %s } },\n'
                     % ('"%s",' % name, '"%s",' % place, el.upper() + ',', len(team), mons))
        o.append('};\n\n')
    o.append('#define GYM_REGIONS %d\n' % len(D.VERSIONS))
    o.append('static const TrainerSet TRAINER_SETS[GYM_REGIONS] = {\n')
    for ver, *_ in D.VERSIONS:
        o.append('  { TRAINERS_%s, "%s" },\n' % (ident(ver), ver))
    o.append('};\n\n')
    o.append('// Hard mode reruns the same ladder with perfect IVs and a smarter AI.\n'
             '#define HARD_IV 31\n#define EASY_IV 16\n')
    open(os.path.join(ROOT, 'trainers.h'), 'w').write(''.join(o))


def rgb565(c):
    r, g, b = c
    return (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)


def hexrgb(h):
    return int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16)


def shade(c, f):
    return tuple(max(0, min(255, int(v * f))) for v in c)


def inside(shape, x, y):
    """Is (x, y), centred at 0 with radius ~1, inside badge shape n?"""
    r = math.hypot(x, y)
    a = math.atan2(y, x)
    if shape == 0:   # disc
        return r <= 1
    if shape == 1:   # diamond
        return abs(x) + abs(y) <= 1.05
    if shape == 2:   # hexagon
        return max(abs(x) * 0.866 + abs(y) * 0.5, abs(y)) <= 0.92
    if shape == 3:   # shield
        if -0.9 <= y <= 0.35:
            return abs(x) <= 0.85
        return y > 0.35 and abs(x) <= 0.85 * (1 - (y - 0.35) / 0.7)
    if shape == 4:   # five-point star
        k = (math.cos(5 * (a + math.pi / 2)) + 1) / 2
        return r <= 0.5 + 0.5 * k
    if shape == 5:   # ring
        return 0.45 <= r <= 1
    if shape == 6:   # triangle
        return y <= 0.75 and abs(x) <= (y + 0.95) * 0.62
    if shape == 7:   # cross
        return (abs(x) <= 0.34 and abs(y) <= 1) or (abs(y) <= 0.34 and abs(x) <= 1)
    return False


def badge(shape, base):
    """32x32 indices into a 5-colour palette: 0 outline, 1 body, 2 shade,
    3 light, 4 the version's gem in the middle; 255 transparent."""
    light = tuple(min(255, v + 90) for v in base)
    pal = [(0x1b, 0x1b, 0x25), base, shade(base, 0.68), light, (0xf4, 0xf8, 0xea)]
    grid = [[255] * PX for _ in range(PX)]
    c = (PX - 1) / 2
    for y in range(PX):
        for x in range(PX):
            u, v = (x - c) / 13.5, (y - c) / 13.5
            if inside(shape, u, v):
                grid[y][x] = 2 if (u + v) > 0.55 else (3 if (u + v) < -0.9 else 1)
    # gem
    for y in range(PX):
        for x in range(PX):
            if grid[y][x] != 255 and math.hypot(x - c, y - c) <= 3.2:
                grid[y][x] = 4
    # outline
    out = [row[:] for row in grid]
    for y in range(PX):
        for x in range(PX):
            if grid[y][x] == 255:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                xx, yy = x + dx, y + dy
                if not (0 <= xx < PX and 0 <= yy < PX) or grid[yy][xx] == 255:
                    out[y][x] = 0
                    break
    return pal, out


def badges():
    o = ['// GENERATED by tools/gen_ladders.py - do not edit\n//\n'
         '// One badge per area boss: eight shapes, coloured by the boss\'s element.\n'
         '// Drawn from geometry, so they are this project\'s own artwork.\n'
         '#pragma once\n#include <stdint.h>\n\n',
         '#define BADGE_PX %d\n#define BADGE_REGIONS %d\n\n' % (PX, len(D.VERSIONS))]
    refs = []
    for vi, (ver, *_r) in enumerate(D.VERSIONS):
        row = []
        for i in range(8):
            name, el, _team = D.LADDERS[ver][i]
            pal, grid = badge(i, hexrgb(D.ELEMENT_ACCENT[el]))
            tag = 'BADGE_%s_%d' % (ident(ver), i)
            o.append('// %s %s\n' % (ver, name))
            o.append('static const uint16_t %s_PAL[%d] = { %s };\n'
                     % (tag, len(pal), ', '.join('0x%04X' % rgb565(p) for p in pal)))
            o.append('static const uint8_t %s_IDX[%d] = {\n' % (tag, PX * PX))
            for r in grid:
                o.append('  ' + ','.join(str(v) for v in r) + ',\n')
            o.append('};\n')
            row.append('{ %s_PAL, %s_IDX }' % (tag, tag))
        refs.append(row)
    o.append('\nstruct BadgeArt { const uint16_t *pal; const uint8_t *idx; };\n')
    o.append('static const BadgeArt BADGES_ART[BADGE_REGIONS][8] = {\n')
    for row in refs:
        o.append('  { %s },\n' % ', '.join(row))
    o.append('};\n')
    open(os.path.join(ROOT, 'badges.h'), 'w').write(''.join(o))


if __name__ == '__main__':
    D.validate()
    trainers()
    badges()
    print('trainers.h + badges.h: %d ladders' % len(D.VERSIONS))
