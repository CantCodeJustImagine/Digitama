#!/usr/bin/env python3
"""Generates dex.h (the Digimon table for the firmware) from digimon_data.py.

  python3 tools/gen_dex.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import digimon_data as D


def rgb565(hexcol):
    r, g, b = int(hexcol[1:3], 16), int(hexcol[3:5], 16), int(hexcol[5:7], 16)
    return (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)


def ident(name):
    return name.replace('.', '').replace(' ', '_')


def main():
    D.validate()
    bn = D.by_num()
    out = []
    w = out.append
    w("#pragma once\n#include <stdint.h>\n\n")
    w("// GENERATED by tools/gen_dex.py from tools/digimon_data.py - do not edit\n\n")
    w("#define DEX_COUNT %d\n\n" % len(D.ROSTER))

    w("// Stages of a Digimon's life. A stage lasts until the next one's entry\n"
      "// level (levels are hours since hatching + 1).\n")
    w("enum : uint8_t { %s, STAGE_COUNT };\n" % ", ".join("ST_" + s for s in D.STAGES))
    w("static const uint8_t STAGE_ENTRY[STAGE_COUNT] = { %s };\n\n"
      % ", ".join(map(str, D.STAGE_ENTRY)))

    w("// Elements: the battle engine's types.\n")
    w("enum PkType : uint8_t {\n  %s,\n  T_NONE = 255\n};\n" %
      ", ".join("T_" + e.upper() for e in D.ELEMENTS))
    w("#define TYPE_COUNT %d\n\n" % len(D.ELEMENTS))
    w("// Element chart in TENTHS (5 weak, 10 neutral, 20 strong). There are no\n"
      "// immunities: a bad matchup is never a wasted turn.\n")
    w("static const uint8_t TYPE_FX[TYPE_COUNT][TYPE_COUNT] = {\n")
    for atk in D.ELEMENTS:
        row = [str(int(D.CHART.get(atk, {}).get(dfn, 1) * 10)) for dfn in D.ELEMENTS]
        w("  { %s },  // %s\n" % (", ".join(f"{v:>2}" for v in row), atk))
    w("};\n\n")

    names = ", ".join('"%s"' % e.upper() for e in D.ELEMENTS)
    w("static const char *const ELEMENT_NAME[TYPE_COUNT] = { %s };\n" % names)
    cols, light = [], []
    for e in D.ELEMENTS:
        h = D.ELEMENT_ACCENT[e]
        r, g, b = int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16)
        cols.append("0x%04X" % rgb565(h))
        light.append('1' if 0.299 * r + 0.587 * g + 0.114 * b > 150 else '0')
    w("// Chip colour per element, and whether it needs dark text on it.\n")
    w("static const uint16_t TYPE_COL[TYPE_COUNT] = { %s };\n" % ", ".join(cols))
    w("static const uint8_t TYPE_COL_LIGHT[TYPE_COUNT] = { %s };\n\n" % ", ".join(light))
    w("// Attributes: Vaccine beats Virus, Virus beats Data, Data beats Vaccine.\n"
      "// FREE (every baby) is neutral both ways.\n")
    w("enum : uint8_t { %s, ATTR_COUNT };\n" % ", ".join("AT_" + a for a in D.ATTRS))
    w("static const char *const ATTR_NAME[ATTR_COUNT] = { %s };\n"
      % ", ".join('"%s"' % a for a in D.ATTRS))
    w("#define ATTR_STRONG_PCT 130\n#define ATTR_WEAK_PCT 80\n")
    w("static inline uint16_t attrEffPct(uint8_t atk, uint8_t def) {\n"
      "  if (atk == AT_FREE || def == AT_FREE || atk >= ATTR_COUNT || def >= ATTR_COUNT) return 100;\n"
      "  if ((atk == AT_VACCINE && def == AT_VIRUS) || (atk == AT_VIRUS && def == AT_DATA) ||\n"
      "      (atk == AT_DATA && def == AT_VACCINE)) return ATTR_STRONG_PCT;\n"
      "  if ((def == AT_VACCINE && atk == AT_VIRUS) || (def == AT_VIRUS && atk == AT_DATA) ||\n"
      "      (def == AT_DATA && atk == AT_VACCINE)) return ATTR_WEAK_PCT;\n"
      "  return 100;\n}\n\n")

    w("// rarity: 0 = only by digivolution, 1 = hatches from a Digi-Egg. The two\n"
      "// higher tiers are unused by the roster but kept for the engine.\n"
      "enum : uint8_t { R_EVO = 0, R_COMUN, R_RARO, R_LEGENDARIO };\n\n")
    w("struct DexEntry {\n"
      "  const char *name;\n"
      "  uint16_t evolvesTo;   // FIRST branch (see EVO_TBL), 0 = nothing leads on\n"
      "  uint8_t evolveLevel;  // level at which a digivolution is offered\n"
      "  uint8_t rarity;       // hatches from an egg if > 0\n"
      "  uint16_t accent;      // RGB565 element colour for the UI\n"
      "  uint8_t bHp, bAtk, bDef, bSpe;\n"
      "  uint8_t bSpA, bSpD;\n"
      "  uint8_t biome;        // 0 meadow 1 beach 2 forest 3 volcano 4 mountain 5 snow\n"
      "  uint8_t type1, type2;  // element; type2 = T_NONE\n"
      "  uint8_t stage;        // ST_*\n"
      "  uint8_t attr;         // AT_*\n"
      "};\n\n")
    w("static const DexEntry DEX_TBL[DEX_COUNT + 1] = {\n")
    w('  { "?", 0, 0, 0, 0x2946, 50, 50, 50, 50, 50, 50, 0, T_NEUTRAL, T_NONE, 0, AT_FREE },  // 0: unused\n')
    hatch = {s for _n, _a, _b, st in D.VERSIONS for s in st}
    for num, ver, spr, disp, stage, attr, el, prof, _m in D.ROSTER:
        acc = rgb565(D.ELEMENT_ACCENT[el])
        rar = 'R_COMUN' if num in hatch else 'R_EVO'
        hp, atk, df, spe, spa, spd = D.base_stats(num)
        bio = D.BIOME_OVERRIDE.get(num, D.ELEMENT_BIOME[el])
        w(f'  {{ "{disp}", {D.first_target(num)}, {D.evolve_level(num)}, {rar}, 0x{acc:04X}, '
          f'{hp}, {atk}, {df}, {spe}, {spa}, {spd}, {bio}, T_{el.upper()}, T_NONE, '
          f'ST_{D.STAGES[stage]}, AT_{attr} }},  // {num} {ver}\n')
    w("};\n\n")

    w("// Digivolution branches, in priority order per source: the first rule\n"
      "// whose conditions hold (and whose target can be drawn) is taken.\n"
      "#define EVO_ANY 255\n"
      "struct DigiEvo {\n"
      "  uint16_t from, to;\n"
      "  uint8_t minCare, maxCare;    // care mistakes\n"
      "  uint8_t minTrain, maxTrain;  // trAtk + trDef + trSpe, capped at 255\n"
      "  uint8_t minWins;             // battles won as the live Digimon\n"
      "};\n")
    w("#define EVO_COUNT %d\n" % len(D.EVOLUTIONS))
    w("static const DigiEvo EVO_TBL[EVO_COUNT] = {\n")
    for f, t, a, b, c, d, wn in D.EVOLUTIONS:
        w(f"  {{ {f}, {t}, {a}, {b}, {c}, {d}, {wn} }},  // {bn[f][3]} -> {bn[t][3]}\n")
    w("};\n\n")

    w("// Which V-Pet version an egg comes from. A version owns a block of the dex\n"
      "// and its egg hatches into the version's Baby I.\n")
    w("struct RegionInfo {\n  const char *name;\n  uint16_t lo, hi;\n"
      "  const int16_t *starters;\n  uint8_t starterCount;\n};\n")
    allstart = sorted({s for _n, _a, _b, st in D.VERSIONS for s in st})
    for name, lo, hi, st in D.VERSIONS:
        w("static const int16_t REGION_START_%s[] = { %s };\n"
          % (ident(name), ", ".join(map(str, st))))
    w("static const int16_t REGION_START_ALL[] = { %s };\n" % ", ".join(map(str, allstart)))
    w("#define REGION_COUNT %d\n" % (len(D.VERSIONS) + 1))
    w("#define REGION_ALL %d\n" % len(D.VERSIONS))
    w("static const RegionInfo REGIONS[REGION_COUNT] = {\n")
    for name, lo, hi, st in D.VERSIONS:
        w('  { "%s", %d, %d, REGION_START_%s, %d },\n' % (name, lo, hi, ident(name), len(st)))
    w('  { "ALL", 1, %d, REGION_START_ALL, %d },\n' % (len(D.ROSTER), len(allstart)))
    w("};\n")

    path = os.path.join(os.path.dirname(__file__), '..', 'dex.h')
    open(path, 'w').write(''.join(out))
    print(f"saved {os.path.normpath(path)} ({len(D.ROSTER)} Digimon, {len(D.EVOLUTIONS)} branches)")


if __name__ == '__main__':
    main()
